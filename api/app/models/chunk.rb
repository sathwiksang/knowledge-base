# A segment of a {Document}'s text content paired with its vector embedding
# for semantic search.
#
# During document processing ({DocumentProcessorService}), the full
# document text is split into overlapping chunks by {TextChunkerService},
# and each chunk is converted into a 768-dimensional vector by
# {EmbeddingService}. These vectors are stored in the +embedding+ column
# (pgvector type) and indexed with an HNSW index for fast approximate
# nearest-neighbour search.
#
# == Resource hierarchy
#
#   User → KnowledgeBase → Document → **Chunk**
#
# == How search works
#
# When a user searches, their query is also embedded into a 768-dim vector.
# pgvector then finds the chunks whose embeddings are closest to the query
# vector using cosine distance. The {SearchService} wraps this logic.
#
# == Table: +chunks+
#
# @!attribute [r] id
#   @return [Integer] primary key (auto-increment)
# @!attribute [rw] content
#   @return [String] the text content of this chunk (NOT NULL)
# @!attribute [rw] chunk_index
#   @return [Integer] 0-based position of this chunk within its parent
#     document. Combined with +document_id+ forms a unique constraint
#     so the same index cannot appear twice for one document.
# @!attribute [rw] embedding
#   @return [Vector] 768-dimensional float vector generated by
#     nomic-embed-text via {EmbeddingService}. Stored as a pgvector
#     +vector(768)+ column. Indexed with HNSW for cosine distance
#     search.
# @!attribute [rw] document_id
#   @return [Integer] foreign key to the parent {Document} (indexed, NOT NULL)
# @!attribute [r] created_at
#   @return [DateTime]
# @!attribute [r] updated_at
#   @return [DateTime]
#
# == Database indexes
#
# - +index_chunks_on_document_id+ — FK lookup
# - +index_chunks_on_document_id_and_chunk_index+ — unique constraint
# - +index_chunks_on_embedding_hnsw+ — HNSW index with +vector_cosine_ops+
#   for fast approximate nearest-neighbour queries
#
# @example Searching for similar chunks (used by SearchService)
#   query_vector = EmbeddingService.new.generate("How does auth work?")
#   chunks = Chunk.search_similar(query_vector, knowledge_base_id: 1, limit: 5)
#   chunks.each { |c| puts c.content }
#
# @see Document Parent model that holds the full text
# @see EmbeddingService Generates the 768-dim vectors
# @see SearchService High-level search interface
# @see TextChunkerService Splits document text into chunks
class Chunk < ApplicationRecord
  # @!method document
  #   @return [Document] the document this chunk was extracted from.
  #     Required — every chunk must belong to a document.
  belongs_to :document

  # Registers the +embedding+ column with the +neighbor+ gem so we can
  # call +nearest_neighbors(:embedding, ...)+ for vector similarity search.
  has_neighbors :embedding

  # Content must be present — a chunk without text has no value.
  validates :content, presence: true

  # chunk_index must be a non-negative integer and unique within its document.
  # This ensures we can reconstruct the original document order and prevents
  # duplicate chunks from being created during reprocessing.
  validates :chunk_index, presence: true,
                          numericality: { only_integer: true, greater_than_or_equal_to: 0 },
                          uniqueness: { scope: :document_id }

  # @!method self.for_knowledge_base(kb_id)
  #   Scope chunks to a specific knowledge base by joining through the
  #   documents table. Used by {SearchService} and {.search_similar} to
  #   ensure search results stay within the correct KB boundary.
  #
  #   @param kb_id [Integer] the knowledge base ID to scope to
  #   @return [ActiveRecord::Relation<Chunk>] chunks belonging to
  #     documents in the given KB
  #
  #   @example
  #     Chunk.for_knowledge_base(1).count # => 87
  scope :for_knowledge_base, ->(kb_id) {
    joins(:document).where(documents: { knowledge_base_id: kb_id })
  }

  # Find the most semantically similar chunks to a query embedding
  # within a single knowledge base.
  #
  # Uses pgvector's cosine distance operator via the +neighbor+ gem's
  # +nearest_neighbors+ method. Results are ordered by similarity
  # (most similar first). Each returned chunk has a +neighbor_distance+
  # attribute that {SearchService} converts to a similarity score.
  #
  # @param query_embedding [Array<Float>] the 768-dim query vector
  # @param knowledge_base_id [Integer] scope results to this KB
  # @param limit [Integer] maximum number of results (default: 5)
  # @return [ActiveRecord::Relation<Chunk>] chunks ordered by cosine
  #   similarity (closest first), with +neighbor_distance+ available
  #
  # @example
  #   query_vec = EmbeddingService.new.generate("authentication")
  #   results = Chunk.search_similar(query_vec, knowledge_base_id: 1, limit: 3)
  #   results.first.neighbor_distance # => 0.1234 (cosine distance)
  def self.search_similar(query_embedding, knowledge_base_id:, limit: 5)
    for_knowledge_base(knowledge_base_id)
      .nearest_neighbors(:embedding, query_embedding, distance: "cosine")
      .limit(limit)
  end
end
